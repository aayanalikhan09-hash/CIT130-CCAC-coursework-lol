public class Course {

    private int courseID;
    private String title;
    private float credits;
    private int capacity;
    
    private int getCourseID(){
        return courseID;
    }
    private String getTitle(){
        return title;
    }
    private float getCredits(){
        return credits;
    }
    private int getCapacity(){
        return capacity;
    }
}
